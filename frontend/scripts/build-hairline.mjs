#!/usr/bin/env node
/**
 * Bundles the Hairline kernel and the homelab's figures into one ES module:
 * `node scripts/build-hairline.mjs`. The kernel is copied unchanged from the
 * hairline-create skill (MIT, see components/homelab/hairline/LICENSE), and
 * each figure is the same file the skill's bench and checks run on. Here
 * each one runs in its own scope, and its hairline({ … }) declaration is
 * collected instead of mounted.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../components/homelab/hairline/', import.meta.url))
const kernel = readFileSync(join(dir, 'kernel.js'), 'utf8').trimEnd()
const names = readdirSync(join(dir, 'figures')).filter(f => f.endsWith('.js')).map(f => f.slice(0, -3)).sort()

const body = names.map((name) => {
  const src = readFileSync(join(dir, 'figures', `${name}.js`), 'utf8').trim()
  return `figures[${JSON.stringify(name)}] = (() => {\n  let spec\n  const hairline = (s) => { spec = s }\n${src}\n  return spec\n})()`
}).join('\n\n')

writeFileSync(join(dir, 'figures.generated.js'), `/* Generated by scripts/build-hairline.mjs. Edit figures/*.js, then run it again. */\n${kernel}\n\nconst figures = {}\n\n${body}\n\nexport { HL, figures }\n`)
console.log(`hairline: ${names.join(', ')}`)
